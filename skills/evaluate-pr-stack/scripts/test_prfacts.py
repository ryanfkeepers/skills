OID = "a" * 40


def file(name, add, dele, status="modified", patch="", **extra):
    return dict(filename=name, additions=add, deletions=dele, status=status, patch=patch, **extra)


def thread(login, typename, resolved, body="fix this", path="a.go", line=3):
    return {"isResolved": resolved, "isOutdated": False, "path": path, "line": line, "originalLine": line,
            "comments": {"nodes": [{"author": {"__typename": typename, "login": login},
                                    "body": body, "url": f"https://x/{login}"}]}}


class FakeGh:
    def __init__(self, files, threads, body="", comments=(), raw="", mergeable="MERGEABLE", contexts=()):
        self.files, self.threads, self.body = files, threads, body
        self.mergeable, self.contexts = mergeable, list(contexts)
        self.comments, self.raw, self.calls = comments, raw, []

    def __call__(self, args):
        self.calls.append(args)
        if args[0] == "api" and args[1] == "graphql":
            return json.dumps({"data": {"repository": {"pullRequest": {
                "title": "t", "body": self.body, "headRefOid": OID, "mergeable": self.mergeable,
                "commits": {"nodes": [{"commit": {"statusCheckRollup": {"contexts": {"nodes": self.contexts}}
                                                  if self.contexts else None}}]},
                "comments": {"nodes": [{"body": c} for c in self.comments]},
                "reviewThreads": {"pageInfo": {"hasNextPage": False, "endCursor": None},
                                  "nodes": self.threads}}}}})
        if args[0] == "api" and "/pulls/" in args[1]:
            return json.dumps(self.files if "page=1" in args[1] else [])
        if args[0] == "api" and "/contents/" in args[1]:
            return self.raw
        raise AssertionError(f"unexpected gh call: {args}")


def facts(**kw):
    return prfacts.cmd_facts(FakeGh(**kw), "o/r", 7)


class LocPoints(unittest.TestCase):
    def test_boundaries(self):
        got = [prfacts.loc_points(n) for n in (0, 499, 500, 699, 700, 799, 800, 5000)]
        self.assertEqual(got, [5, 5, 3, 3, 1, 1, 0, 0])


class Facts(unittest.TestCase):
    def test_counts_additions_plus_deletions(self):
        out = facts(files=[file("a.go", 100, 20), file("a_test.go", 50, 0)], threads=[])
        self.assertEqual(out["loc_counted"], 170)
        self.assertEqual(out["loc_points"], 5)

    def test_generated_by_path_is_excluded(self):
        out = facts(files=[file("a.go", 100, 0), file("go.sum", 900, 0), file("api/x.pb.go", 400, 0)],
                    threads=[])
        self.assertEqual(out["loc_counted"], 100)
        self.assertEqual({g["path"] for g in out["generated_excluded"]}, {"go.sum", "api/x.pb.go"})

    def test_generated_by_marker_in_patch(self):
        patch = "@@ -0,0 +1,2 @@\n+// Code generated by foo. DO NOT EDIT.\n+package x"
        out = facts(files=[file("x.go", 900, 0, status="added", patch=patch)], threads=[])
        self.assertEqual(out["loc_counted"], 0)
        self.assertEqual(out["generated_excluded"][0]["why"], "marker")

    def test_generated_by_marker_in_head_of_large_modified_file(self):
        gh = FakeGh(files=[file("x.go", 300, 10, patch="@@ -50 +50 @@\n+y")], threads=[],
                    raw="// Code generated by foo. DO NOT EDIT.\npackage x\n")
        out = prfacts.cmd_facts(gh, "o/r", 7)
        self.assertEqual(out["loc_counted"], 0)

    def test_small_file_is_not_probed(self):
        gh = FakeGh(files=[file("x.go", 5, 5)], threads=[])
        prfacts.cmd_facts(gh, "o/r", 7)
        self.assertFalse([c for c in gh.calls if "/contents/" in c[1]])

    def test_handwritten_large_file_is_counted(self):
        gh = FakeGh(files=[file("x.go", 600, 0)], threads=[], raw="package x\n")
        out = prfacts.cmd_facts(gh, "o/r", 7)
        self.assertEqual(out["loc_counted"], 600)
        self.assertEqual(out["loc_points"], 3)

    def test_files_sorted_largest_first_and_rename_kept(self):
        out = facts(files=[file("a.go", 1, 0), file("b.go", 9, 0, status="renamed", previous_filename="c.go")],
                    threads=[])
        self.assertEqual([f["path"] for f in out["files"]], ["b.go", "a.go"])
        self.assertEqual(out["files"][0]["renamed_from"], "c.go")


class AiThreads(unittest.TestCase):
    def test_only_bot_threads_count(self):
        out = facts(files=[], threads=[
            thread("copilot-pull-request-reviewer", "Bot", False),
            thread("coderabbitai", "Bot", True),
            thread("alice", "User", False),
        ])
        self.assertEqual(out["ai_threads_total"], 2)
        self.assertEqual(out["ai_threads_unresolved"], 1)

    def test_no_threads(self):
        out = facts(files=[], threads=[])
        self.assertEqual((out["ai_threads_total"], out["ai_threads_unresolved"]), (0, 0))

    def test_body_is_collapsed_and_truncated(self):
        out = facts(files=[], threads=[thread("bot", "Bot", False, body="x\n" * 500)])
        self.assertLessEqual(len(out["ai_threads"][0]["body"]), prfacts.BODY_LIMIT)
        self.assertNotIn("\n", out["ai_threads"][0]["body"])

    def test_deleted_author_is_not_a_bot(self):
        t = thread("x", "Bot", False)
        t["comments"]["nodes"][0]["author"] = None
        self.assertEqual(facts(files=[], threads=[t])["ai_threads_total"], 0)


class VisualizationLinks(unittest.TestCase):
    def test_found_in_body_and_comments(self):
        out = facts(files=[], threads=[], body="see https://claude.ai/artifact/abc-123 ok",
                    comments=["and https://claude.ai/code/artifact/def_456", "nothing"])
        self.assertEqual(out["visualization_links"],
                         ["https://claude.ai/artifact/abc-123", "https://claude.ai/code/artifact/def_456"])

    def test_none(self):
        self.assertEqual(facts(files=[], threads=[], body=None)["visualization_links"], [])


def check_run(name, conclusion, required):
    return {"__typename": "CheckRun", "name": name, "conclusion": conclusion, "isRequired": required}


def status(name, state, required):
    return {"__typename": "StatusContext", "context": name, "state": state, "isRequired": required}


class Blockers(unittest.TestCase):
    def test_clean(self):
        out = facts(files=[], threads=[])
        self.assertEqual(out["mergeable"], "MERGEABLE")
        self.assertEqual((out["blocking_ci_failures"], out["other_ci_failures"]), ([], []))

    def test_conflict_is_reported(self):
        self.assertEqual(facts(files=[], threads=[], mergeable="CONFLICTING")["mergeable"], "CONFLICTING")

    def test_required_failure_blocks_optional_does_not(self):
        out = facts(files=[], threads=[], contexts=[
            check_run("build", "FAILURE", True),
            check_run("lint", "TIMED_OUT", False),
            status("ci/legacy", "ERROR", True),
            check_run("test", "SUCCESS", True),
            check_run("slow", None, True),
        ])
        self.assertEqual(out["blocking_ci_failures"], ["build", "ci/legacy"])
        self.assertEqual(out["other_ci_failures"], ["lint"])


class Cli(unittest.TestCase):
    def test_error_is_json_and_exit_1(self):
        def boom(args):
            raise prstack.GhError("nope")
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            code = prfacts.main(["facts", "-R", "o/r", "1"], gh=boom)
        self.assertEqual(code, 1)
        self.assertEqual(json.loads(buf.getvalue()), {"status": "error", "message": "nope"})

    def test_bad_repo_is_error(self):
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            code = prfacts.main(["facts", "-R", "bad repo", "1"], gh=lambda a: "")
        self.assertEqual(code, 1)


